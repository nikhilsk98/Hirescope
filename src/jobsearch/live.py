"""dashboard/live.js: what the open dashboard re-reads every few seconds (it can't ask anything: file://, CSP
connect-src 'none'), written by the hirescope:// launcher and the resume-queue worker:

  queue      active items in order (+ the last day's finished ones): job, status, attempts, times, message
  worker     running | paused (a HireScope run is writing) | idle | stopped, with a heartbeat
  excel      the applications Excel file: ok | pending (open in Excel; saved beside it, applied on the next sync) | off
  launcher   the last link handled (time + what happened), so the page knows a click arrived
  bucket_at / sync_at   when the Bucket / your statuses last changed in SQLite (the page then re-reads sync.js)

dashboard/launcher.js says whether the launcher is installed (scripts/install_launcher.sh writes it; the page shows
a one-time setup banner otherwise). Both are rewritten atomically and are never needed for the page to work.
"""
from __future__ import annotations

import json
import sqlite3
from pathlib import Path

from . import paths
from .storage import db

LAUNCHER_APP = Path.home() / "Applications" / "HireScope Launcher.app"


def _atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def _meta(conn, key: str) -> dict:
    try:
        return json.loads(db.get_meta(conn, key) or "{}")
    except (ValueError, sqlite3.Error):
        return {}


def payload(conn) -> dict:
    try:
        from resume_builder import queue
        q = queue.items(conn)
    except (ImportError, sqlite3.OperationalError):
        q = []
    keep = ("id", "job_pk", "company", "title", "status", "regenerate", "attempts", "added_at", "started_at",
            "finished_at", "message", "result", "origin", "batch")
    try:
        bucket_at = conn.execute("SELECT MAX(updated_at) FROM bucket").fetchone()[0]
        questions = conn.execute("SELECT COUNT(DISTINCT keyword) FROM resume_questions WHERE answered_at IS NULL"
                                 ).fetchone()[0]
    except sqlite3.OperationalError:
        bucket_at, questions = None, 0
    return {"generated_at": db.utcnow(), "queue": [{k: r.get(k) for k in keep} for r in q],
            "worker": _meta(conn, "queue_worker"), "excel": _meta(conn, "excel_applications"),
            "launcher": _meta(conn, "launcher_last"), "bucket_at": bucket_at, "sync_at": db.get_meta(conn, "sync_at"),
            "questions_open": questions}


def write(conn, path: Path | None = None) -> Path:
    path = path or (paths.DASHBOARD / "live.js")
    _atomic(path, "// Generated by the HireScope launcher / resume queue — live state for the open dashboard. Do not edit.\n"
            f"(window.__hsLive || function (d) {{ window.LIVE = d; }})({json.dumps(payload(conn), ensure_ascii=False)});\n")
    return path


def write_launcher_js(installed: bool | None = None, path: Path | None = None) -> Path:
    """installed=None: whether the launcher app is in ~/Applications now."""
    installed = LAUNCHER_APP.exists() if installed is None else installed
    path = path or (paths.DASHBOARD / "launcher.js")
    _atomic(path, "// Generated by scripts/install_launcher.sh (and each run) — is the hirescope:// launcher installed?\n"
            f"window.HS_LAUNCHER = {json.dumps({'installed': bool(installed), 'version': 1})};\n")
    return path


def ensure_files(conn) -> None:
    """Each dashboard publish: live.js and launcher.js exist (the page loads them; a missing file is a console error)."""
    write(conn)
    write_launcher_js()
